//! Injectable sources for time, randomness, and UUIDv7 identity generation.
//!
//! The domain defines ports only. Production adapters own access to the system
//! clock and operating-system randomness, while tests can supply deterministic
//! implementations without introducing those capabilities into domain logic.

use crate::{UtcTimestamp, UuidV7, ValueObjectError};

/// A source of control-plane UTC timestamps.
pub trait Clock {
    /// Returns the current control-plane time.
    fn now(&self) -> UtcTimestamp;
}

/// A source of opaque random bytes.
pub trait RandomSource {
    /// The error reported when random bytes cannot be supplied.
    type Error;

    /// Fills `destination` completely with random bytes.
    fn fill_bytes(&mut self, destination: &mut [u8]) -> Result<(), Self::Error>;
}

/// A source of UUIDv7 values generated by the application layer.
pub trait UuidV7Source {
    /// The error reported when an ID cannot be generated.
    type Error;

    /// Returns the next UUIDv7 value.
    fn next_uuid_v7(&mut self) -> Result<UuidV7, Self::Error>;
}

/// The failure modes of a [`UuidV7Generator`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum UuidV7GeneratorError<RandomError> {
    /// The injected random source could not provide a complete UUID payload.
    Random(RandomError),
    /// The injected clock returned a timestamp that UUIDv7 cannot represent.
    Timestamp(ValueObjectError),
}

/// A composable UUIDv7 source backed by injected time and randomness.
///
/// This generator intentionally does not reach the system clock or random
/// device itself. Infrastructure supplies those adapters in production and
/// deterministic fixtures supply them in tests.
pub struct UuidV7Generator<'clock, 'random, C, R> {
    clock: &'clock C,
    random: &'random mut R,
}

impl<'clock, 'random, C, R> UuidV7Generator<'clock, 'random, C, R> {
    /// Combines a clock and random source into a UUIDv7 source.
    pub const fn new(clock: &'clock C, random: &'random mut R) -> Self {
        Self { clock, random }
    }
}

impl<C, R> UuidV7Source for UuidV7Generator<'_, '_, C, R>
where
    C: Clock,
    R: RandomSource,
{
    type Error = UuidV7GeneratorError<R::Error>;

    fn next_uuid_v7(&mut self) -> Result<UuidV7, Self::Error> {
        let mut random = [0_u8; 10];
        self.random
            .fill_bytes(&mut random)
            .map_err(UuidV7GeneratorError::Random)?;
        let timestamp = u64::try_from(self.clock.now().unix_millis())
            .map_err(|_| UuidV7GeneratorError::Timestamp(ValueObjectError::TimestampOutOfRange))?;
        UuidV7::from_timestamp_and_random(timestamp, random)
            .map_err(UuidV7GeneratorError::Timestamp)
    }
}
