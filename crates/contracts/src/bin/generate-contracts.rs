#![forbid(unsafe_code)]

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

use contracts::ErrorEnvelope;
use schemars::{Schema, schema_for};
use serde_json::{Map, Value};

const GENERATED_HEADER: &str = "// @generated by crates/contracts. DO NOT EDIT.\n";

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let output = output_directory()?;
    let schema_directory = output.join("schema");
    fs::create_dir_all(&schema_directory)?;

    let error_schema = schema_for!(ErrorEnvelope);
    write_json(
        &schema_directory.join("error-envelope.schema.json"),
        &error_schema,
    )?;

    let schema_value = serde_json::to_value(&error_schema)?;
    let typescript = render_typescript(&[("ErrorEnvelope", schema_value)])?;
    fs::write(output.join("index.ts"), typescript)?;
    Ok(())
}

fn output_directory() -> Result<PathBuf, String> {
    let mut arguments = env::args_os().skip(1);
    let output = arguments
        .next()
        .ok_or_else(|| "usage: generate-contracts <output-directory>".to_owned())?;
    if arguments.next().is_some() {
        return Err("usage: generate-contracts <output-directory>".to_owned());
    }
    Ok(PathBuf::from(output))
}

fn write_json(path: &Path, schema: &Schema) -> Result<(), Box<dyn std::error::Error>> {
    let mut bytes = serde_json::to_vec_pretty(schema)?;
    bytes.push(b'\n');
    fs::write(path, bytes)?;
    Ok(())
}

fn render_typescript(roots: &[(&str, Value)]) -> Result<String, String> {
    let mut output = String::from(GENERATED_HEADER);
    output.push_str("// Source of truth: Rust DTOs + Schemars JSON Schema.\n\n");
    for (name, schema) in roots {
        output.push_str("export type ");
        output.push_str(name);
        output.push_str(" = ");
        output.push_str(&schema_to_typescript(schema, 0)?);
        output.push_str(";\n");
    }
    Ok(output)
}

fn schema_to_typescript(schema: &Value, depth: usize) -> Result<String, String> {
    let object = schema
        .as_object()
        .ok_or_else(|| "schema node must be an object".to_owned())?;

    if let Some(any_of) = object.get("anyOf").and_then(Value::as_array) {
        return any_of
            .iter()
            .map(|entry| schema_to_typescript(entry, depth))
            .collect::<Result<Vec<_>, _>>()
            .map(|entries| entries.join(" | "));
    }

    match object.get("type") {
        Some(Value::String(kind)) => render_type(kind, object, depth),
        Some(Value::Array(kinds)) => kinds
            .iter()
            .map(|kind| {
                kind.as_str()
                    .ok_or_else(|| "schema type array must contain strings".to_owned())
                    .and_then(|kind| render_type(kind, object, depth))
            })
            .collect::<Result<Vec<_>, _>>()
            .map(|entries| entries.join(" | ")),
        None => Ok("unknown".to_owned()),
        _ => Err("schema type must be a string or string array".to_owned()),
    }
}

fn render_type(kind: &str, object: &Map<String, Value>, depth: usize) -> Result<String, String> {
    match kind {
        "string" => Ok("string".to_owned()),
        "boolean" => Ok("boolean".to_owned()),
        "integer" | "number" => Ok("number".to_owned()),
        "null" => Ok("null".to_owned()),
        "array" => object
            .get("items")
            .ok_or_else(|| "array schema is missing items".to_owned())
            .and_then(|items| schema_to_typescript(items, depth))
            .map(|items| format!("Array<{items}>")),
        "object" => render_object(object, depth),
        other => Err(format!("unsupported JSON Schema type: {other}")),
    }
}

fn render_object(object: &Map<String, Value>, depth: usize) -> Result<String, String> {
    let Some(properties) = object.get("properties").and_then(Value::as_object) else {
        return Ok("Record<string, unknown>".to_owned());
    };
    let required = object
        .get("required")
        .and_then(Value::as_array)
        .map(|items| items.iter().filter_map(Value::as_str).collect::<Vec<_>>())
        .unwrap_or_default();
    let indent = "  ".repeat(depth + 1);
    let closing_indent = "  ".repeat(depth);
    let mut result = String::from("{\n");
    for (name, property) in properties {
        result.push_str(&indent);
        result.push_str(name);
        if !required.contains(&name.as_str()) {
            result.push('?');
        }
        result.push_str(": ");
        result.push_str(&schema_to_typescript(property, depth + 1)?);
        result.push_str(";\n");
    }
    result.push_str(&closing_indent);
    result.push('}');
    Ok(result)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn converts_nullable_object_fields_without_any() {
        let schema = serde_json::json!({
            "type": "object",
            "required": ["field"],
            "properties": {
                "field": { "type": ["string", "null"] },
                "details": { "type": "object" }
            }
        });
        let rendered = schema_to_typescript(&schema, 0).expect("supported schema");
        assert_eq!(
            rendered,
            "{\n  details?: Record<string, unknown>;\n  field: string | null;\n}"
        );
        assert!(!rendered.contains("any"));
    }
}
